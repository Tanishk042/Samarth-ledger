import { jsPDF } from 'jspdf'
import { formatDate, formatINR } from './utils'

const INK = [20, 20, 19]
const ORANGE = [193, 64, 0]
const MUTED = [117, 108, 102]

function header(doc, title, subtitle) {
  doc.setFillColor(...ORANGE)
  doc.rect(0, 0, 210, 22, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(15)
  doc.text('SAMARTH LEDGER', 16, 10)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.text('AICTE · Security Deposit & FDR Management', 16, 16)
  doc.setTextColor(...INK)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text(title, 16, 38)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...MUTED)
  doc.text(subtitle, 16, 45)
}

function footer(doc, note) {
  doc.setDrawColor(224, 219, 215)
  doc.line(16, 275, 194, 275)
  doc.setFontSize(7.5)
  doc.setTextColor(...MUTED)
  doc.text(note, 16, 282, { maxWidth: 178 })
  doc.text('Illustrative demo document · not a bank instrument', 16, 288)
}

export function generateRenewalPdf({ fdr, college, bank, now = new Date() }) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  header(doc, 'AI-prepared FDR renewal draft', `Prepared ${formatDate(now)} · requires institution confirmation and bank action`)

  doc.setFillColor(246, 243, 241)
  doc.roundedRect(16, 54, 178, 58, 3, 3, 'F')
  doc.setTextColor(...INK)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.text('Deposit summary', 22, 64)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  const rows = [
    ['Institution', college?.name || '—'],
    ['FDR number', fdr.fdNumber],
    ['Bank / branch', `${bank?.name || '—'} · ${fdr.branch}`],
    ['Principal', formatINR(fdr.amount)],
    ['Maturity date', formatDate(fdr.maturityDate)],
    ['Interest rate', `${fdr.interestRate}% p.a.`],
  ]
  rows.forEach(([k, v], i) => {
    doc.setTextColor(...MUTED)
    doc.text(k, 22, 73 + i * 6.2)
    doc.setTextColor(...INK)
    doc.text(String(v), 72, 73 + i * 6.2)
  })

  doc.setTextColor(...INK)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.text('Proposed action', 16, 126)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.text(
    [
      '1. Confirm the renewal instruction in the institution portal before the maturity date.',
      '2. The bank issues a fresh FDR with a new FD number and updated maturity date.',
      '3. Upload the fresh receipt, or authorise an Account Aggregator fetch, so a new fingerprint can be anchored.',
      '4. The previous token is marked superseded; it is never transferred.',
    ],
    16,
    134,
    { maxWidth: 178, lineHeightFactor: 1.6 },
  )

  doc.setFillColor(255, 246, 240)
  doc.roundedRect(16, 182, 178, 42, 3, 3, 'F')
  doc.setTextColor(...ORANGE)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  doc.text('Human check required', 22, 192)
  doc.setTextColor(...INK)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  doc.text(
    'This draft was generated by a deterministic template engine using deposit metadata. It is not a renewal instruction until an authorised institution officer and the bank both act. Verify all amounts against the original receipt.',
    22,
    199,
    { maxWidth: 166, lineHeightFactor: 1.5 },
  )

  footer(doc, 'Generated by the Samarth Ledger prototype. Deposit data is illustrative. No personal data is written to the ledger.')
  return { dataUri: doc.output('datauristring'), filename: `Renewal_Draft_${fdr.id}.pdf` }
}

export function generateReleaseCertificate({ fdr, college, bank, keys, now = new Date() }) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  header(doc, 'Dual-lock release certificate', `Issued ${formatDate(now)} · ledger-anchored event`)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(...INK)
  doc.text('Release identity', 16, 60)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  const rows = [
    ['FDR ID', fdr.id],
    ['Institution', college?.name || '—'],
    ['Bank', bank?.name || '—'],
    ['Amount', formatINR(fdr.amount)],
    ['Maturity', formatDate(fdr.maturityDate)],
    ['Released on', formatDate(now)],
  ]
  rows.forEach(([k, v], i) => {
    doc.setTextColor(...MUTED)
    doc.text(k, 16, 70 + i * 7)
    doc.setTextColor(...INK)
    doc.text(String(v), 60, 70 + i * 7)
  })

  doc.setFillColor(246, 243, 241)
  doc.roundedRect(16, 120, 178, 70, 3, 3, 'F')
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.text('Two independent signatures', 22, 131)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  doc.text(`Key 1 · AI release agent (rules engine)`, 22, 142)
  doc.setFont('courier', 'normal')
  doc.setFontSize(7.5)
  doc.text(String(keys?.key1?.signature || '—').slice(0, 62), 22, 148)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  doc.text(`Key 2 · AICTE officer (${keys?.key2?.method || 'unknown method'})`, 22, 160)
  doc.setFont('courier', 'normal')
  doc.setFontSize(7.5)
  doc.text(String(keys?.key2?.signature || '—').slice(0, 62), 22, 166)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8.5)
  doc.text(
    'The ledger rejects a release with only one key. Both signatures, the pause-switch state and a timestamp are written as ledger events before funds can move.',
    22,
    181,
    { maxWidth: 164, lineHeightFactor: 1.5 },
  )

  doc.setTextColor(...ORANGE)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  doc.text('AI helps. Humans decide.', 16, 210)

  footer(doc, 'Demo certificate. Not a payment instruction. Verify the ledger block hash in the public explorer.')
  return { dataUri: doc.output('datauristring'), filename: `Release_Certificate_${fdr.id}.pdf` }
}

export function downloadDataUri(dataUri, filename) {
  const a = document.createElement('a')
  a.href = dataUri
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
}
