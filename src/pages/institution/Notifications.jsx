import { useMemo, useState } from 'react'
import { Link, useNavigate } from 'react-router-dom'
import {
  ArrowRight,
  Bell,
  CalendarClock,
  Check,
  CheckCheck,
  CircleAlert,
  Clock3,
  FileText,
  Inbox,
  RefreshCw,
  Search,
  ShieldAlert,
  Sparkles,
  Timer,
} from 'lucide-react'
import {
  Badge,
  Button,
  Card,
  EmptyState,
  Eyebrow,
  InlineNote,
  Input,
  SimBadge,
  StatusPill,
  Tabs,
} from '../../components/ui/primitives'
import { useStore } from '../../store/useStore'
import { toast } from '../../store/useToast'
import { formatDateTime, matchesQuery } from '../../lib/utils'
import { cn } from '../../lib/utils'

const FILTERS = [
  { value: 'all', label: 'All' },
  { value: 'unread', label: 'Unread' },
  { value: 'reminder', label: 'Reminders' },
  { value: 'review', label: 'Review' },
  { value: 'release', label: 'Release' },
  { value: 'risk', label: 'Risk' },
]

function groupFor(type = '') {
  if (type.startsWith('reminder') || type.startsWith('maturity')) return 'reminder'
  if (type.startsWith('release')) return 'release'
  if (type.startsWith('risk') || type.startsWith('proof') || type.startsWith('replacement')) return 'risk'
  if (type.startsWith('review') || type.startsWith('fdr') || type.startsWith('replacement')) return 'review'
  return 'other'
}

const TONE = {
  reminder: 'amber',
  release: 'orange',
  risk: 'red',
  review: 'blue',
  other: 'sand',
}

export default function Notifications() {
  const navigate = useNavigate()
  const notifications = useStore((s) => s.notifications)
  const fdrs = useStore((s) => s.fdrs)
  const clockOffsetDays = useStore((s) => s.clockOffsetDays)
  const markRead = useStore((s) => s.markNotificationRead)
  const markAll = useStore((s) => s.markAllNotificationsRead)
  const advanceClock = useStore((s) => s.advanceClock)
  const runReminders = useStore((s) => s.runReminders)
  const [filter, setFilter] = useState('all')
  const [query, setQuery] = useState('')
  const [busy, setBusy] = useState(false)

  const mine = useMemo(
    () => notifications.filter((n) => n.audience !== 'officer'),
    [notifications],
  )

  const counts = useMemo(() => {
    const result = { all: mine.length, unread: mine.filter((n) => !n.read).length }
    for (const item of FILTERS) {
      if (item.value === 'all' || item.value === 'unread') continue
      result[item.value] = mine.filter((n) => groupFor(n.type) === item.value).length
    }
    return result
  }, [mine])

  const list = useMemo(() => {
    return mine
      .filter((n) => {
        if (filter === 'unread') return !n.read
        if (filter !== 'all') return groupFor(n.type) === filter
        return true
      })
      .filter((n) => matchesQuery(`${n.title} ${n.body} ${n.type} ${n.fdrId || ''}`, query))
      .sort((a, b) => String(b.at).localeCompare(String(a.at)))
  }, [mine, filter, query])

  const openNotification = (n) => {
    markRead(n.id)
    if (n.fdrId) navigate(`/app/institution/fdr/${n.fdrId}`)
    else toast('This notification has no linked record.', { tone: 'default' })
  }

  const fastForward = async (days) => {
    setBusy(true)
    try {
      await advanceClock(days)
    } finally {
      setBusy(false)
    }
  }

  const remindersNow = async () => {
    setBusy(true)
    try {
      const result = await runReminders()
      toast(
        result.created
          ? `${result.created} reminder or escalation event(s) created.`
          : 'No new reminders in the current window.',
        { tone: result.created ? 'success' : 'default' },
      )
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="space-y-5">
      <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <Eyebrow>Notification centre</Eyebrow>
            <SimBadge>Seeded + live events</SimBadge>
          </div>
          <h1 className="display mt-2 text-3xl sm:text-[40px]">
            What needs <em className="serif-accent">your attention.</em>
          </h1>
          <p className="mt-2 max-w-2xl text-[13px] leading-relaxed text-muted">
            Maturity reminders, review outcomes and release updates. Reminders are generated by real in-app logic when the scenario clock
            moves.
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          <Button variant="outline" onClick={markAll} disabled={!counts.unread}>
            <CheckCheck size={14} /> Mark all read
          </Button>
          <Button onClick={remindersNow} disabled={busy}>
            {busy ? <RefreshCw size={14} className="animate-spin" /> : <Bell size={14} />}
            Run reminder engine
          </Button>
        </div>
      </div>

      <div className="grid gap-4 xl:grid-cols-[1fr_320px]">
        <Card className="overflow-hidden">
          <div className="flex flex-col gap-3 border-b border-line p-4">
            <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
              <Tabs
                items={FILTERS.map((item) => ({ ...item, count: counts[item.value] }))}
                value={filter}
                onChange={setFilter}
              />
              <div className="relative sm:w-[235px]">
                <Search size={14} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-muted" />
                <Input
                  value={query}
                  onChange={(e) => setQuery(e.target.value)}
                  placeholder="Search notifications"
                  className="py-2 pl-9 text-[12px]"
                  aria-label="Search notifications"
                />
              </div>
            </div>
            <div className="flex items-center justify-between text-[10px] text-muted">
              <span>{list.length} of {mine.length} notifications · {counts.unread} unread</span>
              <span className="flex items-center gap-1"><Inbox size={11} /> Institution inbox</span>
            </div>
          </div>

          {list.length ? (
            <ul className="divide-y divide-line/70">
              {list.map((n) => {
                const group = groupFor(n.type)
                const fdr = n.fdrId ? fdrs.find((f) => f.id === n.fdrId) : null
                return (
                  <li key={n.id}>
                    <button
                      type="button"
                      onClick={() => openNotification(n)}
                      className={cn(
                        'flex w-full items-start gap-3 px-4 py-4 text-left transition hover:bg-paper/60',
                        !n.read && 'bg-accent/[0.035]',
                      )}
                    >
                      <span
                        className={cn(
                          'mt-0.5 grid h-9 w-9 shrink-0 place-items-center rounded-xl',
                          group === 'reminder'
                            ? 'bg-amber-500/10 text-amber-700 dark:text-amber-300'
                            : group === 'release'
                              ? 'bg-accent/10 text-accent'
                              : group === 'risk'
                                ? 'bg-danger/10 text-danger'
                                : 'bg-sky-500/10 text-sky-700 dark:text-sky-300',
                        )}
                      >
                        {group === 'reminder' ? (
                          <CalendarClock size={16} />
                        ) : group === 'release' ? (
                          <Clock3 size={16} />
                        ) : group === 'risk' ? (
                          <ShieldAlert size={16} />
                        ) : (
                          <FileText size={16} />
                        )}
                      </span>
                      <span className="min-w-0 flex-1">
                        <span className="flex flex-wrap items-center gap-1.5">
                          {!n.read && <span className="h-1.5 w-1.5 rounded-full bg-accent" aria-label="Unread" />}
                          <span className="text-[12px] font-semibold leading-snug">{n.title}</span>
                          <Badge tone={TONE[group]}>{group}</Badge>
                          {fdr && <StatusPill status={fdr.status} />}
                        </span>
                        <span className="mt-1 block text-[11px] leading-relaxed text-muted">{n.body}</span>
                        <span className="mt-1 block font-mono text-[9px] text-muted/70">
                          {formatDateTime(n.at)}
                          {n.fdrId ? ` · ${n.fdrId}` : ''}
                        </span>
                      </span>
                      <span className="mt-1 flex shrink-0 items-center gap-1 text-[10px] font-semibold text-muted">
                        {n.fdrId ? 'Open' : 'Read'} <ArrowRight size={12} />
                      </span>
                    </button>
                  </li>
                )
              })}
            </ul>
          ) : (
            <EmptyState
              icon={query ? Search : Inbox}
              title={query ? 'No notifications match that search' : 'Nothing in this filter'}
              description="Try another category, clear the search, or move the scenario clock to generate real reminders."
              action={
                <Button
                  variant="outline"
                  onClick={() => {
                    setFilter('all')
                    setQuery('')
                  }}
                >
                  Clear filters
                </Button>
              }
              className="m-4 border-0 bg-transparent"
            />
          )}

          <div className="flex flex-wrap items-center justify-between gap-2 border-t border-line px-4 py-3 text-[10px] text-muted">
            <span className="flex items-center gap-1.5"><Check size={11} /> Opening a notification marks it read.</span>
            <span>{mine.filter((n) => n.read).length} already read</span>
          </div>
        </Card>

        <div className="space-y-4">
          <Card className="p-4">
            <div className="flex items-start justify-between gap-2">
              <div>
                <p className="text-[10px] font-bold uppercase tracking-[0.13em] text-muted">Time machine</p>
                <p className="mt-1 text-sm font-semibold">Move the scenario clock</p>
              </div>
              <Timer size={16} className="text-accent" />
            </div>
            <p className="mt-2 text-[11px] leading-relaxed text-muted">
              The app runs real reminder logic for 60-day, 30-day, maturity and escalation events, and prepares renewal drafts within 60
              days of maturity.
            </p>
            <div className="mt-3 grid grid-cols-3 gap-1.5">
              {[10, 30, 60].map((days) => (
                <Button key={days} size="sm" variant="outline" onClick={() => fastForward(days)} disabled={busy}>
                  +{days}d
                </Button>
              ))}
            </div>
            {busy && (
              <p className="mt-2 flex items-center gap-1.5 text-[10px] font-semibold text-muted">
                <RefreshCw size={11} className="animate-spin" /> Running reminder logic…
              </p>
            )}
            <div className="mt-3 rounded-2xl bg-paper/60 p-3">
              <p className="text-[9px] font-bold uppercase tracking-[0.12em] text-muted">Scenario date</p>
              <p className="mt-1 font-mono text-[11px] font-semibold">
                {formatDateTime(new Date(Date.now() + clockOffsetDays * 86400000))}
              </p>
              <p className="mt-1 text-[10px] text-muted">{clockOffsetDays} day offset from today</p>
            </div>
          </Card>

          <Card className="p-4">
            <p className="text-[10px] font-bold uppercase tracking-[0.13em] text-muted">Reminder policy</p>
            <ul className="mt-2.5 space-y-2 text-[10px] leading-relaxed text-muted">
              <li className="flex items-start gap-2"><CalendarClock size={11} className="mt-0.5 shrink-0 text-amber-600" /> 60 days: renewal draft prepared and institution notified.</li>
              <li className="flex items-start gap-2"><CalendarClock size={11} className="mt-0.5 shrink-0 text-amber-600" /> 30 days: confirm renewal or request release.</li>
              <li className="flex items-start gap-2"><CircleAlert size={11} className="mt-0.5 shrink-0 text-danger" /> At maturity: status becomes renewal due.</li>
              <li className="flex items-start gap-2"><ShieldAlert size={11} className="mt-0.5 shrink-0 text-danger" /> After 7 days: escalated to an AICTE officer.</li>
            </ul>
            <InlineNote className="mt-3" icon={Sparkles}>
              All dates and amounts are illustrative. The reminder engine is real application logic over seeded data.
            </InlineNote>
          </Card>

          <Card className="p-4">
            <p className="text-[10px] font-bold uppercase tracking-[0.13em] text-muted">Related</p>
            <div className="mt-2 space-y-1.5">
              <Link to="/app/institution" className="flex items-center justify-between rounded-xl px-2 py-2 text-[11px] font-semibold transition hover:bg-paper/60">
                All deposits <ArrowRight size={12} className="text-muted" />
              </Link>
              <Link to="/app/institution/new" className="flex items-center justify-between rounded-xl px-2 py-2 text-[11px] font-semibold transition hover:bg-paper/60">
                Add a new FDR <ArrowRight size={12} className="text-muted" />
              </Link>
              <Link to="/app/officer/releases" className="flex items-center justify-between rounded-xl px-2 py-2 text-[11px] font-semibold transition hover:bg-paper/60">
                Release queue <ArrowRight size={12} className="text-muted" />
              </Link>
            </div>
          </Card>
        </div>
      </div>
    </div>
  )
}
